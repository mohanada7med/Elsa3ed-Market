async function main() {
  const uri = process.env.MONGODB_URI || 'mongodb://localhost:27017/Elsa3ed_market';
  const dbName = process.env.MONGODB_DB || 'Elsa3ed_market';
  const client = new MongoClient(uri);

  try {
    await client.connect();
    const db = client.db(dbName);
    console.log(`Connected to MongoDB (${dbName}). Inserting new colloquial Upper Egypt figures...`);

    for (const person of NEW_PEOPLE) {
      const now = new Date().toISOString();
      const doc = {
        ...person,
        createdAt: now,
        updatedAt: now
      };

      await db.collection('wah_local_people').updateOne(
        { id: person.id },
        { $set: doc },
        { upsert: true }
      );
      console.log(`✓ Added/Updated: ${person.name} (${person.originVillage})`);
    }

    const total = await db.collection('wah_local_people').countDocuments();
    console.log(`\n🎉 Total figures in wah_local_people now: ${total}`);
  } catch (err) {
    console.error('Error inserting people:', err);
  } finally {
    await client.close();
  }
}

main();
