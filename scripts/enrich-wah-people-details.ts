async function enrichWahPeople() {
  const uri = process.env.MONGODB_URI;
  const dbName = process.env.MONGODB_DB || 'Elsa3ed_market';
  if (!uri) {
    console.error('MONGODB_URI is not set');
    process.exit(1);
  }

  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db(dbName);
    const collection = db.collection('wah_local_people');

    console.log(`Connected to DB: ${dbName}`);
    console.log(`Enriching figures with deep biographical details...`);

    let enrichedCount = 0;
    for (const [id, details] of Object.entries(DETAILED_PEOPLE_ENRICHMENTS)) {
      const result = await collection.updateOne(
        { id },
        {
          $set: {
            originVillage: details.originVillage,
            biography: details.biography,
            bio: details.biography,
            keyMilestones: details.keyMilestones,
            famousWorksOrActs: details.famousWorksOrActs,
            localImpact: details.localImpact,
            famousAnecdote: details.famousAnecdote,
            updatedAt: new Date().toISOString()
          }
        }
      );
      if (result.matchedCount > 0) {
        enrichedCount++;
        console.log(`✓ Enriched: ${id} (${details.originVillage})`);
      }
    }

    console.log(`\n🎉 Successfully enriched ${enrichedCount} figures with comprehensive biographical data!`);
  } catch (err) {
    console.error('Enrichment error:', err);
  } finally {
    await client.close();
  }
}

enrichWahPeople();
