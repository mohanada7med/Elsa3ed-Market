async function main() {
  const uri = process.env.MONGODB_URI || 'mongodb://localhost:27017/Elsa3ed_market';
  const dbName = process.env.MONGODB_DB || 'Elsa3ed_market';
  const client = new MongoClient(uri);

  try {
    await client.connect();
    const db = client.db(dbName);
    console.log(`Connected to MongoDB (${dbName}). Inserting 6 iconic Upper Egypt figures in colloquial Arabic...`);

    for (const person of SIX_MORE_FIGURES) {
      await db.collection('wah_local_people').updateOne(
        { id: person.id },
        { $set: person },
        { upsert: true }
      );
      console.log(`✓ Added/Updated: ${person.name} (${person.villageOrOrigin})`);
    }

    const total = await db.collection('wah_local_people').countDocuments();
    console.log(`🎉 Total figures in wah_local_people now: ${total}`);
  } catch (err) {
    console.error('Error inserting figures:', err);
  } finally {
    await client.close();
  }
}

main();
